//! The pack format reference in `docs/packs/reference` (decision 0030), written by
//! `involo-pack reference` (`just pack-docs`): one page per pack file from its JSON Schema, as
//! `describe` reads it, and every problem code from the code table. `just ci` fails when the
//! committed pages differ from what this writes, so the reference never drifts from the code.

use std::fmt::Write as _;

use crate::Code;
use crate::codes::GROUPS;
use crate::describe::{Description, Part, describe, known_files};

/// The first lines of every page: its license, and that it is generated. The tags are split in
/// this source so that license tools read them as the pages' tags, not this file's.
const HEADER: &str = concat!(
    "<!--\nSPDX-",
    "FileCopyrightText: 2026 offbyonce\nSPDX-",
    "License-Identifier: MIT\n\n",
    "Generated by `just pack-docs` from the JSON Schemas and the code table: do not edit. Change the\ndoc comments in the Rust types (or crates/involo-pack/src/codes.rs) and run `just pack-docs`.\n-->\n"
);

/// Every page, as `(file name, text)`: `index.md`, one page per pack file, and `codes.md`.
pub fn pages() -> Vec<(String, String)> {
    let files: Vec<Description> = known_files()
        .into_iter()
        .filter_map(|f| describe(f).ok())
        .collect();
    let mut out = vec![("index.md".to_owned(), index(&files))];
    out.extend(files.iter().map(|d| (page_name(&d.file), file_page(d))));
    out.push(("codes.md".to_owned(), codes_page()));
    out
}

/// A pack file's page: `flight.yaml` → `flight.md`, `pack.json` → `pack-json.md`,
/// `lists/<name>.yaml` → `lists.md`.
pub fn page_name(file: &str) -> String {
    let base = file
        .split('/')
        .next()
        .unwrap_or(file)
        .trim_end_matches(".yaml");
    format!("{}.md", base.replace('.', "-"))
}

fn index(files: &[Description]) -> String {
    let mut out = String::from(HEADER);
    out.push_str("# Pack format reference\n\n");
    out.push_str("Every file a pack can hold, with every field it takes, and every problem code `involo-pack check`\ngives. The same facts come from `involo-pack describe <file>` and `involo-pack explain <code>`, and\nthe JSON Schemas in `schemas/` give editors autocomplete. The guide that explains them is\n[one folder up](../README.md).\n\n");
    out.push_str("| File | Schema | What it is |\n| --- | --- | --- |\n");
    for d in files {
        let about = d
            .parts
            .first()
            .and_then(|p| p.description.as_deref())
            .map_or_else(String::new, |t| cell(&first_sentence(t)));
        let _ = writeln!(
            out,
            "| [`{}`]({}) | `{}` | {about} |",
            d.file,
            page_name(&d.file),
            d.schema_file
        );
    }
    let _ = writeln!(
        out,
        "\n[Problem codes](codes.md): what each of the {} codes `involo-pack check` gives means, and how to fix it.",
        Code::ALL.len()
    );
    out
}

fn file_page(d: &Description) -> String {
    let mut out = String::from(HEADER);
    let _ = writeln!(out, "# `{}`\n", d.file);
    let _ = writeln!(
        out,
        "Schema: `schemas/{}`. [All files](index.md).\n",
        d.schema_file
    );
    let names: Vec<&str> = d.parts.iter().skip(1).map(|p| p.name.as_str()).collect();
    for (n, part) in d.parts.iter().enumerate() {
        if n == 0 {
            out.push_str("## The file\n\n");
        } else {
            let _ = writeln!(out, "## {}\n", part.name);
        }
        part_body(&mut out, part, &names);
    }
    out
}

fn part_body(out: &mut String, part: &Part, names: &[&str]) {
    if let Some(desc) = &part.description {
        let _ = writeln!(out, "{}\n", one_line(desc));
    }
    if !part.fields.is_empty() {
        out.push_str("| Field | Takes | Required | Default | What it is |\n| --- | --- | --- | --- | --- |\n");
        for f in &part.fields {
            let _ = writeln!(
                out,
                "| `{}` | {} | {} | {} | {} |",
                f.name,
                linked(&f.kind, names),
                if f.required { "yes" } else { "" },
                f.default
                    .as_deref()
                    .map_or_else(String::new, |d| format!("`{}`", d.replace('|', "\\|"))),
                f.description.as_deref().map_or_else(String::new, cell)
            );
        }
        out.push('\n');
    }
    if !part.values.is_empty() {
        out.push_str("| Value | What it means |\n| --- | --- |\n");
        for (word, desc) in &part.values {
            let _ = writeln!(
                out,
                "| `{word}` | {} |",
                desc.as_deref().map_or_else(String::new, cell)
            );
        }
        out.push('\n');
    }
}

fn codes_page() -> String {
    let mut out = String::from(HEADER);
    out.push_str("# Problem codes\n\n");
    let _ = writeln!(
        out,
        "Every problem `involo-pack check` (and the app, when it installs a pack) can report has a stable code.\nA code never changes meaning and is never reused. `involo-pack explain <code>` prints the same entry.\nThere are {} codes. [All files](index.md).\n",
        Code::ALL.len()
    );
    for (prefix, title) in GROUPS {
        let codes: Vec<_> = Code::ALL
            .iter()
            .map(|c| c.info())
            .filter(|i| i.code.starts_with(prefix))
            .collect();
        if codes.is_empty() {
            continue;
        }
        let _ = writeln!(out, "## {prefix}xx: {title}\n");
        for info in codes {
            let _ = writeln!(
                out,
                "### {}: {}\n\n{}\n\nHow to fix it: {}\n",
                info.code, info.title, info.explain, info.hint
            );
        }
    }
    out
}

/// A type in words, with each part of this file it names linked to its section.
fn linked(kind: &str, names: &[&str]) -> String {
    let mut out = String::new();
    let mut word = String::new();
    let flush = |word: &mut String, out: &mut String| {
        if names.contains(&word.as_str()) {
            let _ = write!(out, "[{word}](#{})", word.to_lowercase());
        } else {
            out.push_str(word);
        }
        word.clear();
    };
    for c in kind.chars() {
        if c.is_alphanumeric() || c == '_' {
            word.push(c);
        } else {
            flush(&mut word, &mut out);
            out.push(c);
        }
    }
    flush(&mut word, &mut out);
    out.replace('|', "\\|")
}

/// Text in a table cell: on one line, with its pipes escaped.
fn cell(text: &str) -> String {
    one_line(text).replace('|', "\\|")
}

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn first_sentence(text: &str) -> String {
    let text = one_line(text);
    // A file's description starts by naming it: "`flight.yaml`: the pack's Flight pages...".
    let text = text.split_once(": ").map_or(text.as_str(), |(head, rest)| {
        if head.starts_with('`') {
            rest
        } else {
            text.as_str()
        }
    });
    let end = text.find(". ").map_or(text.len(), |i| i + 1);
    let mut s = text[..end].to_owned();
    if let Some(first) = s.get(..1) {
        s.replace_range(..1, &first.to_uppercase());
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_pack_file_has_a_page_with_every_field() {
        let pages = pages();
        for file in known_files() {
            let name = page_name(file);
            let (_, text) = pages
                .iter()
                .find(|(n, _)| *n == name)
                .unwrap_or_else(|| panic!("no page for {file}"));
            let d = describe(file).unwrap();
            for part in &d.parts {
                for f in &part.fields {
                    assert!(
                        text.contains(&format!("| `{}` |", f.name)),
                        "{file}: {}",
                        f.name
                    );
                }
                for (word, _) in &part.values {
                    assert!(text.contains(&format!("| `{word}` |")), "{file}: {word}");
                }
            }
            let index = &pages[0].1;
            assert!(index.contains(&format!("]({name})")), "index links {name}");
        }
        // One page per file, the index and the codes; no two files share a page.
        assert_eq!(pages.len(), known_files().len() + 2);
    }

    #[test]
    fn every_code_is_on_the_codes_page_in_its_group() {
        let (_, text) = pages().into_iter().find(|(n, _)| n == "codes.md").unwrap();
        for code in Code::ALL {
            let info = code.info();
            assert!(
                GROUPS.iter().any(|(p, _)| info.code.starts_with(p)),
                "{} is in no group",
                info.code
            );
            assert!(
                text.contains(&format!("### {}: {}", info.code, info.title)),
                "{}",
                info.code
            );
            assert!(text.contains(info.hint), "{}", info.code);
        }
    }

    #[test]
    fn a_type_links_the_parts_it_names() {
        assert_eq!(
            linked("list of FlightField", &["FlightField"]),
            "list of [FlightField](#flightfield)"
        );
        assert_eq!(linked("one of a, b", &["FlightField"]), "one of a, b");
        assert_eq!(page_name("lists/<name>.yaml"), "lists.md");
        assert_eq!(page_name("pack.json"), "pack-json.md");
        assert_eq!(page_name("panel-states.yaml"), "panel-states.md");
    }
}
